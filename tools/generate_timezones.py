#!/usr/bin/env python3
"""Generate package/contents/ui/code/TimeZoneData.js from the system's tz database.

QML's JavaScript has no Intl, so time zone math (TimeZone.js) works from the POSIX TZ rule at
the end of each TZif file (eg: "EST5EDT,M3.2.0,M11.1.0"): the zone's current rules. Zones whose
rules changed since TABLE_START also get the transitions from then until the last change, so
recent dates are right too. Older dates use the current rules.

Usage: python3 tools/generate_timezones.py [zoneinfo dir]
"""
import json
import os
import re
import struct
import sys
import zoneinfo

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'package', 'contents', 'ui', 'code', 'TimeZoneData.js')


TABLE_START = 1704067200 # 2024-01-01 UTC


def read_tzif(path):
	"""(POSIX rule, [(utc seconds, offset minutes, abbreviation)]) from a TZif v2+ file."""
	with open(path, 'rb') as f:
		data = f.read()
	if not data.startswith(b'TZif') or data[4:5] < b'2' or not data.endswith(b'\n'):
		return None, []
	counts = struct.unpack('>6l', data[20:44])
	isut, isstd, leap, timecnt, typecnt, charcnt = counts
	pos = 44 + timecnt * 5 + typecnt * 6 + charcnt + leap * 8 + isstd + isut # Skip the v1 data
	isut, isstd, leap, timecnt, typecnt, charcnt = struct.unpack('>6l', data[pos + 20:pos + 44])
	pos += 44
	times = struct.unpack('>%dq' % timecnt, data[pos:pos + 8 * timecnt])
	pos += 8 * timecnt
	indexes = data[pos:pos + timecnt]
	pos += timecnt
	types = [struct.unpack('>lBB', data[pos + 6 * i:pos + 6 * i + 6]) for i in range(typecnt)]
	pos += 6 * typecnt
	chars = data[pos:pos + charcnt]
	def type_of(i):
		utoff, _isdst, idx = types[i]
		return (utoff // 60, chars[idx:chars.index(b'\0', idx)].decode('ascii'))
	transitions = [(t,) + type_of(i) for t, i in zip(times, indexes)]
	footer = data[:-1].rsplit(b'\n', 1)[-1].decode('ascii')
	return footer or None, transitions


def posix_types(rule):
	"""The (offset, abbreviation) pairs of a POSIX rule, eg: {(-300, 'EST'), (-240, 'EDT')}."""
	m = re.match(r'^(<[^>]*>|[A-Za-z]{3,})([+-]?\d{1,2}(?::\d{1,2}){0,2})(<[^>]*>|[A-Za-z]{3,})?([+-]?\d{1,2}(?::\d{1,2}){0,2})?', rule)
	if not m:
		return set()
	def minutes(text):
		sign = -1 if text.startswith('-') else 1
		parts = [int(p) for p in text.lstrip('+-').split(':')] + [0, 0]
		return -sign * (parts[0] * 60 + parts[1]) # POSIX: west of UTC
	std = (minutes(m.group(2)), m.group(1).strip('<>'))
	out = {std}
	if m.group(3):
		out.add((minutes(m.group(4)) if m.group(4) else std[0] + 60, m.group(3).strip('<>')))
	return out


def recent_table(rule, transitions):
	"""Transitions since TABLE_START up to the last one the rule alone doesn't give (a change of
	rules), with the type in force at TABLE_START first; [] when the rule covers them all."""
	tail = posix_types(rule)
	last = -1
	for i, (t, offset, abbr) in enumerate(transitions):
		if t < TABLE_START:
			continue
		before = transitions[i - 1][1:] if i > 0 else None
		if (offset, abbr) not in tail or (before is not None and before not in tail):
			last = i
	if last < 0:
		return []
	table = []
	first = [t for t in transitions if t[0] < TABLE_START]
	if first:
		table.append((TABLE_START,) + first[-1][1:])
	for t, offset, abbr in transitions[:last + 1]:
		if t >= TABLE_START:
			table.append((t, offset, abbr))
	return table


def tab_zones(path):
	zones = set()
	if not os.path.exists(path):
		return zones
	with open(path, encoding='utf-8') as f:
		for line in f:
			if line.startswith('#') or not line.strip():
				continue
			zones.add(line.split('\t')[2].strip())
	return zones


def main():
	zoneinfo_dir = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo'
	rules = {}
	tables = {}
	for name in sorted(zoneinfo.available_timezones()):
		path = os.path.join(zoneinfo_dir, name)
		if not os.path.isfile(path):
			continue
		rule, transitions = read_tzif(path)
		if rule:
			rules[name] = rule
			table = recent_table(rule, transitions)
			if table:
				tables[name] = table
	# The picker: the canonical zones of the zone tables (one or more per country), and UTC.
	picker = tab_zones(os.path.join(zoneinfo_dir, 'zone1970.tab')) | tab_zones(os.path.join(zoneinfo_dir, 'zone.tab'))
	picker = sorted(z for z in picker if z in rules)
	if 'UTC' in rules:
		picker.append('UTC')
	if len(rules) < 300 or len(picker) < 300:
		sys.exit('Too few zones found in %s' % zoneinfo_dir)

	lines = [
		'.pragma library',
		'// Generated by tools/generate_timezones.py from the tz database: do not edit.',
		'// rules: IANA zone id -> POSIX TZ rule (see TimeZone.js). recent: zones whose rules changed',
		'// lately -> [[UTC minutes, offset minutes, abbreviation], ...] until the last change.',
		'// pickerZones: the zones to choose from.',
		'',
		'var rules = {',
	]
	for name in sorted(rules):
		lines.append('\t%s: %s,' % (json.dumps(name), json.dumps(rules[name])))
	lines.append('}')
	lines.append('')
	lines.append('var recent = {')
	for name in sorted(tables):
		lines.append('\t%s: [%s],' % (json.dumps(name), ', '.join('[%d, %d, %s]' % (t // 60, o, json.dumps(a)) for t, o, a in tables[name])))
	lines.append('}')
	lines.append('')
	lines.append('var pickerZones = [')
	for name in picker:
		lines.append('\t%s,' % json.dumps(name))
	lines.append(']')
	with open(OUT, 'w', encoding='utf-8') as f:
		f.write('\n'.join(lines) + '\n')
	print('%d zones (%d with recent changes), %d in the picker -> %s' % (len(rules), len(tables), len(picker), OUT))


if __name__ == '__main__':
	main()
